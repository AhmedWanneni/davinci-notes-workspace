#!/usr/bin/env bash
# links.sh — Multi-platform release download links (macOS, Windows, Linux)
set -euo pipefail

REPO_SLUG="AhmedWanneni/davinci-notes-workspace"

links_fetch_release() {
  local tag="${1:-}"
  if [[ -z "$tag" ]]; then
    # Discover latest release tag from repo or git tags
    tag="$(git describe --tags --abbrev=0 2>/dev/null || echo "v0.1.0")"
  fi
  printf "%s" "$tag"
}

links_display_for_tag() {
  local repo_root="$1"
  local tag="$2"
  local base_url="https://github.com/${REPO_SLUG}/releases/download/${tag}"
  local release_url="https://github.com/${REPO_SLUG}/releases/tag/${tag}"
  local latest_url="https://github.com/${REPO_SLUG}/releases/latest"

  # Standardized asset names generated by Tauri release pipeline
  local mac_arm="Sophia_${tag#v}_aarch64.dmg"
  local mac_x64="Sophia_${tag#v}_x64.dmg"
  local win_exe="Sophia_${tag#v}_x64-setup.exe"
  local linux_appimage="Sophia_${tag#v}_amd64.AppImage"
  local linux_deb="Sophia_${tag#v}_amd64.deb"
  local checksums="SHA256SUMS.txt"

  # Check which assets are physically present on GitHub if gh CLI is available
  local gh_assets=""
  if command -v gh >/dev/null 2>&1; then
    gh_assets="$(gh release view "$tag" --json assets -q '.assets[].name' 2>/dev/null || true)"
  fi

  ui_banner
  status_render_bar "$repo_root"
  ui_section "Release Download Links (${tag})" "🔗"

  printf "  ${C_BOLD}GitHub Release Page:${C_RESET} ${C_CYAN}%s${C_RESET}\n" "$release_url"
  printf "  ${C_MUTED}All installer assets for desktop platforms are listed below:${C_RESET}\n\n"

  # Helper to print each platform asset
  _print_asset() {
    local num="$1" os_icon="$2" os_name="$3" file_name="$4"
    local url="${base_url}/${file_name}"
    local status_badge="${C_MUTED}[Standard URL]${C_RESET}"

    if [[ -n "$gh_assets" ]]; then
      if echo "$gh_assets" | grep -Fxq "$file_name"; then
        status_badge="${C_GREEN}✔ Available on GitHub${C_RESET}"
      else
        status_badge="${C_YELLOW}⏳ Building / Pending in CI${C_RESET}"
      fi
    fi

    printf "  ${C_BOLD}%s)${C_RESET} %s ${C_BOLD}%-26s${C_RESET} %b\n" "$num" "$os_icon" "$os_name" "$status_badge"
    printf "     ${C_MUTED}File:${C_RESET} %s\n" "$file_name"
    printf "     ${C_CYAN}%s${C_RESET}\n\n" "$url"
  }

  _print_asset "1" "🍏" "macOS (Apple Silicon M1-M4)" "$mac_arm"
  _print_asset "2" "🍏" "macOS (Intel x64)" "$mac_x64"
  _print_asset "3" "🪟" "Windows (x64 Installer)" "$win_exe"
  _print_asset "4" "🐧" "Linux (Universal AppImage)" "$linux_appimage"
  _print_asset "5" "🐧" "Linux (Debian / Ubuntu .deb)" "$linux_deb"
  _print_asset "6" "🔐" "SHA256 Checksums" "$checksums"
  _print_asset "7" "🌐" "Release Page on GitHub" ""

  printf "  ${C_MUTED}───────────────────────────────────────────────────────────${C_RESET}\n"
  printf "  ${C_BOLD}Actions:${C_RESET} Enter number (1-7) to copy/open link, 'o' to open release in browser, 'b' to go back.\n\n"
  printf "  ${C_BOLD}Select action:${C_RESET} "

  local act
  read -r act || return 0

  local chosen_file="" chosen_label=""
  case "$act" in
    1) chosen_file="$mac_arm"; chosen_label="macOS Apple Silicon DMG" ;;
    2) chosen_file="$mac_x64"; chosen_label="macOS Intel DMG" ;;
    3) chosen_file="$win_exe"; chosen_label="Windows Installer" ;;
    4) chosen_file="$linux_appimage"; chosen_label="Linux AppImage" ;;
    5) chosen_file="$linux_deb"; chosen_label="Linux DEB Package" ;;
    6) chosen_file="$checksums"; chosen_label="SHA256 Checksums" ;;
    7|o|O)
      ui_open_url "$release_url"
      ui_pause
      return 0
      ;;
    b|B|"") return 0 ;;
    *)
      ui_warn "Invalid selection."
      sleep 1
      return 0
      ;;
  esac

  local target_url="${base_url}/${chosen_file}"
  printf "\n  ${C_BOLD}Selected:${C_RESET} %s\n" "$chosen_label"
  printf "  ${C_CYAN}%s${C_RESET}\n\n" "$target_url"
  printf "  ${C_BOLD}c)${C_RESET} Copy direct link to clipboard\n"
  printf "  ${C_BOLD}o)${C_RESET} Open link in web browser\n"
  printf "  ${C_BOLD}d)${C_RESET} Download file locally via curl\n"
  printf "  ${C_BOLD}b)${C_RESET} Cancel\n\n"
  printf "  ${C_BOLD}Choose action:${C_RESET} "

  local sub_act
  read -r sub_act || return 0
  case "$sub_act" in
    c|C)
      ui_copy_clipboard "$target_url" "$chosen_label link"
      ui_pause
      ;;
    o|O)
      ui_open_url "$target_url"
      ui_pause
      ;;
    d|D)
      local dest_dir
      dest_dir="$(installer_get_dir "$repo_root")"
      local dest_path="${dest_dir}/${chosen_file}"
      ui_info "Downloading to ${dest_path}..."
      if curl -fL "$target_url" -o "$dest_path"; then
        ui_success "Downloaded to ${dest_path}"
        if [[ "$dest_path" == *.AppImage ]]; then
          chmod +x "$dest_path"
        fi
        printf "\n  Would you like to install / run this package now? [Y/n]: "
        local ins
        read -r ins || ins="y"
        if [[ "$ins" =~ ^[Yy]$ || -z "$ins" ]]; then
          installer_perform_install "$dest_path"
        fi
      else
        ui_error "Download failed. Asset may still be compiling in CI matrix."
      fi
      ui_pause
      ;;
    *) ;;
  esac
}

links_menu() {
  local repo_root="$1"
  cd "$repo_root"

  local tag
  tag="$(links_fetch_release "")"

  while true; do
    ui_banner
    status_render_bar "$repo_root"
    ui_section "Platform Release & Installer Links" "🔗"

    printf "  ${C_BOLD}Current Release Tag:${C_RESET} ${C_GREEN}%s${C_RESET}\n\n" "$tag"
    printf "  ${C_BOLD}1)${C_RESET} View & Copy Download Links (${C_CYAN}Mac DMG, Windows, Linux${C_RESET})\n"
    printf "  ${C_BOLD}2)${C_RESET} Open GitHub Latest Release in Browser\n"
    printf "  ${C_BOLD}3)${C_RESET} Switch Release Tag (${C_CYAN}Current: %s${C_RESET})\n" "$tag"
    printf "  ${C_BOLD}4)${C_RESET} View Live Assets on GitHub (${C_CYAN}via gh release view${C_RESET})\n"
    printf "  ${C_BOLD}b)${C_RESET} Back to Main Menu\n\n"
    printf "  ${C_BOLD}Select an option:${C_RESET} "

    local choice
    read -r choice || break
    case "$choice" in
      1)
        links_display_for_tag "$repo_root" "$tag"
        ;;
      2)
        ui_open_url "https://github.com/${REPO_SLUG}/releases/tag/${tag}"
        ui_pause
        ;;
      3)
        printf "\n  Enter release tag (e.g. v0.1.0 or v0.1.0-rc.1): "
        local custom_tag
        read -r custom_tag || custom_tag=""
        if [[ -n "$custom_tag" ]]; then
          tag="$custom_tag"
          ui_success "Switched to release tag: $tag"
          sleep 1
        fi
        ;;
      4)
        if command -v gh >/dev/null 2>&1; then
          ui_info "Fetching GitHub release details for ${tag}..."
          gh release view "$tag" || ui_warn "Release ${tag} not found."
        else
          ui_warn "GitHub CLI (gh) not installed."
        fi
        ui_pause
        ;;
      b|B|"")
        break
        ;;
      *)
        ui_warn "Invalid selection."
        sleep 1
        ;;
    esac
  done
}
